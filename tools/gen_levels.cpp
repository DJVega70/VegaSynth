// Measures every program's loudness and writes Source/Levels.h so all 100 programs sit at a similar level.
// Build:  g++ -O2 -std=c++17 -DPCM_NO_TRIM -o gen_levels tools/gen_levels.cpp && ./gen_levels > Source/Levels.h
#include "../Source/Engine.h"
#include <cstdio>
using namespace pcm;
int main()
{
    Engine e; e.prepare(48000); e.g.mode = ProgramMode;
    const double target = 0.14;                  // loudest 50 ms RMS, about -17 dBFS
    std::printf("#pragma once\n// Generated by tools/gen_levels.cpp\nconstexpr float kLevelTrim[100] = {\n");
    for (int p = 0; p < kNumPrograms; ++p)
    {
        double sumDb = 0; int cnt = 0;
        for (int note : { 36, 60, 84 })
        {
            e.allNotesOff(); std::vector<float> w(24000), w2(24000); e.process(w.data(), w2.data(), 24000);
            e.parts[0] = PartCfg(); e.parts[0].prog = p; e.parts[0].level = 1.0f;
            e.noteOn(0, note, 0.8f);
            std::vector<float> l(192000), r(192000);
            for (int i = 0; i < 192000; i += 500) e.process(l.data() + i, r.data() + i, 500);
            double best = 1e-9;
            for (int i = 0; i + 2400 <= 192000; i += 1200) { double s = 0; for (int k = 0; k < 2400; ++k) s += (double) l[(size_t) (i + k)] * l[(size_t) (i + k)]; best = std::max(best, std::sqrt(s / 2400)); }
            sumDb += 20 * std::log10(best); ++cnt;
        }
        const double meanDb = sumDb / cnt, trim = std::max(0.3, std::min(3.0, target / std::pow(10.0, meanDb / 20)));
        std::printf("%.3ff,%s", trim, (p % 10 == 9) ? "\n" : " ");
    }
    std::printf("};\n");
}
